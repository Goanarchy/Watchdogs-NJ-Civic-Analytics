interface LanguageContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  toggleLang: () => void;
  t: (key: CopyKey, vars?: Record<string, string | number>) => string;
  formatNumber: (value: number) => string;
  formatDate: (iso: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

function interpolate(
  template: string,
  vars?: Record<string, string | number>,
): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : match,
  );
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      // Permite abrir la app directamente en un idioma: index.html?lang=es
      const fromUrl = new URLSearchParams(window.location.search).get("lang");
      if (fromUrl === "es" || fromUrl === "en") return fromUrl;
    } catch {
      // URL no disponible.
    }
    try {
      const saved =
        localStorage.getItem(STORAGE_KEY) ??
        localStorage.getItem(LEGACY_STORAGE_KEY);
      if (saved === "es" || saved === "en") return saved;
    } catch {
      // localStorage may be unavailable.
    }
    return "en";
  });

  useEffect(() => {
    document.documentElement.lang = lang;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      // Ignore storage errors.
    }
  }, [lang]);

  const setLang = useCallback((next: Lang) => setLangState(next), []);
  const toggleLang = useCallback(
    () => setLangState((current) => (current === "en" ? "es" : "en")),
    [],
  );

  const value = useMemo<LanguageContextValue>(() => {
    const dictionary = lang === "es" ? es : en;
    const numberFormatter = new Intl.NumberFormat(
      lang === "es" ? "es-US" : "en-US",
    );
    const dateFormatter = new Intl.DateTimeFormat(
      lang === "es" ? "es-US" : "en-US",
      { day: "numeric", month: "long", year: "numeric" },
    );

    return {
      lang,
      setLang,
      toggleLang,
      t: (key, vars) => interpolate(dictionary[key] ?? en[key] ?? key, vars),
      formatNumber: (value) => numberFormatter.format(value),
      formatDate: (iso) => dateFormatter.format(new Date(iso)),
    };
  }, [lang, setLang, toggleLang]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useI18n(): LanguageContextValue {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useI18n must be used within LanguageProvider");
  }
  return context;
}
